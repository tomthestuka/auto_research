"""Emit the lead x co-lead grid table from the batch records. Numbers are never transcribed.

    python -m benchmarks.author_bench.table_grid

Writes ``papers/FANGZ/tables/grid_leadcolead.tex``, which ``main.tex`` inputs. Re-running it after
a re-measurement updates the table; nothing in the manuscript holds a hand-copied count.

Each cell carries the co-lead rejection total over the arm's trials, and is shaded by the arm's
commit rate, so the reader sees both quantities at once: how much the reviewer objected, and what
that cost the arm.
"""

from __future__ import annotations

import json
import statistics as st
from collections import defaultdict
from pathlib import Path

BATCH = Path("logs/dev/author-bench/20260826T022253Z/records.jsonl")
#: The paper consumes the fragment; the generator lives with the benchmark it reads (user,
#: 2026-08-27: benchmark retrievals and plotters stay together, never in scratch code).
OUT = Path(__file__).resolve().parents[2] / "papers/FANGZ/tables/grid_leadcolead.tex"

LEADS = ["claude-opus-5", "gpt-5.6-sol", "glm-5.3", "qwen3.8-max"]
COLEADS = ["claude-opus-5", "gpt-5.6-sol", "glm-5.3", "qwen3.8-max", "deepseek-v4-pro"]


def shade(commit_rate: float) -> str:
    """Cell shading by commit rate. Five steps, light = every trial committed.

    Greyscale rather than a hue ramp: the table must survive a monochrome print, and a green/red
    ramp would also imply that committing is good and not committing is bad, which is exactly the
    reading the honest-failure policy rejects (a non-commit is a correct outcome).
    """
    if commit_rate >= 1.0:
        return "white"
    if commit_rate >= 0.8:
        return "black!8"
    if commit_rate >= 0.6:
        return "black!18"
    if commit_rate >= 0.4:
        return "black!30"
    return "black!45"


def main() -> int:
    records = [json.loads(line) for line in BATCH.read_text().splitlines() if line.strip()]
    cells: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for record in records:
        cells[(record["lead"], record["colead"])].append(record)

    rows: list[str] = []
    for lead in LEADS:
        parts = [f"\\texttt{{{lead}}}"]
        for colead in COLEADS:
            trials = cells.get((lead, colead), [])
            if not trials:
                parts.append("---")
                continue
            rejections = sum(t.get("review_rejections", 0) for t in trials)
            committed = sum(1 for t in trials if t["status"] == "committed")
            # No correlation marker: the diagonal IS the lead-correlated arm and the last column IS
            # the author-correlated one, both readable off the axes. Annotating them restated the
            # table's own geometry and cost a caption sentence to explain (user, 2026-08-27).
            parts.append(
                f"\\cellcolor{{{shade(committed / len(trials))}}}"
                f"{rejections} ({committed}/{len(trials)})"
            )
        rows.append(" & ".join(parts) + " \\\\")

    total = sum(len(v) for v in cells.values())
    spend = sum(r["cost_usd"] for r in records)
    errors = sum(1 for r in records if r["status"] == "error")
    median_minutes = st.median([r["duration_s"] / 60 for r in records])

    body = "\n".join(rows)
    header = " & ".join(f"\\texttt{{{c}}}" for c in COLEADS)
    OUT.write_text(
        "% GENERATED by benchmarks/author_bench/table_grid.py -- do not edit by hand.\n"
        f"% source: {BATCH}\n"
        "\\begin{table*}\n"
        "\\centering\n"
        "\\caption{Co-lead rejections in the lead $\\times$ co-lead grid, with the arm's commit\n"
        "count in parentheses and cells shaded by commit rate. The author is pinned to\n"
        "\\texttt{deepseek-v4-flash} in all twenty arms and the brief is fixed, so each arm varies\n"
        "only the analyst lead and the reviewer. $N=5$ per arm. Rejections are totals over the\n"
        "arm, not per trial. No arm has a reviewer sharing both the lead's vendor and the author's,\n"
        "since the author's vendor is not eligible to lead. Arms differ in the count of trials\n"
        f"reaching a verdict, where a vendor returned no parseable verdict ({errors} of {total}).}}\n"
        "\\label{t:leadcolead}\n"
        "\\small\n"
        "\\begin{tabular}{@{}l" + "c" * len(COLEADS) + "@{}}\n"
        "\\hline\n"
        f"Analyst lead & \\multicolumn{{{len(COLEADS)}}}{{c}}{{Co-lead (reviewer)}} \\\\\n"
        f" & {header} \\\\\n"
        "\\hline\n"
        f"{body}\n"
        "\\hline\n"
        "\\end{tabular}\n"
        "\\end{table*}\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT}")
    print(f"  {total} trials, US${spend:.2f}, {errors} unparseable verdicts, "
          f"median {median_minutes:.0f} min/trial")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
